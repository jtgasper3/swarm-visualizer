#!/bin/sh
# Downloads the frontend's third-party libraries into static/vendor, from where
# they are compiled into the server along with the rest of the frontend. The
# dashboard then needs nothing from any other site.
#
# To update a library, change its version here, run this script, and review the
# result: vendor.sha256 records what was downloaded, and a test checks the
# files against it.
set -eu
cd "$(dirname "$0")"

VUE=3.5.43
VUETIFY=3.13.6
VUEUSE=12.8.2
MDI=7.4.47

npm=https://cdn.jsdelivr.net/npm
dest=static/vendor

fetch() { # url, path under $dest
	mkdir -p "$dest/$(dirname "$2")"
	curl -fsSL --retry 3 -o "$dest/$2" "$1"
}

rm -rf "$dest"

fetch "$npm/vue@$VUE/dist/vue.esm-browser.prod.js" vue/vue.esm-browser.prod.js
fetch "$npm/vue@$VUE/LICENSE" vue/LICENSE

fetch "$npm/vuetify@$VUETIFY/dist/vuetify.esm.js" vuetify/vuetify.esm.js
fetch "$npm/vuetify@$VUETIFY/dist/vuetify.min.css" vuetify/vuetify.min.css
fetch "$npm/vuetify@$VUETIFY/LICENSE.md" vuetify/LICENSE.md

# index.mjs is the file the packages publish. The .min.mjs the CDN also offers
# is generated by the CDN, so there is nothing to check it against.
fetch "$npm/@vueuse/shared@$VUEUSE/index.mjs" vueuse/shared/index.mjs
fetch "$npm/@vueuse/shared@$VUEUSE/LICENSE" vueuse/shared/LICENSE
fetch "$npm/@vueuse/core@$VUEUSE/index.mjs" vueuse/core/index.mjs
fetch "$npm/@vueuse/core@$VUEUSE/LICENSE" vueuse/core/LICENSE

# The stylesheet finds the font at ../fonts/, so the two keep that layout. It
# lists older formats as well; every browser that can run the page takes woff2.
fetch "$npm/@mdi/font@$MDI/css/materialdesignicons.min.css" mdi/css/materialdesignicons.min.css
fetch "$npm/@mdi/font@$MDI/fonts/materialdesignicons-webfont.woff2" mdi/fonts/materialdesignicons-webfont.woff2
fetch "$npm/@mdi/font@$MDI/LICENSE" mdi/LICENSE

# Roboto. The stylesheet is generated for the browser that asks, so ask as a
# current one to be given woff2, then point it at local copies of the files.
roboto=https://fonts.bunny.net/roboto/files/
agent="Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36"
mkdir -p "$dest/roboto/files"
curl -fsSL --retry 3 -A "$agent" "https://fonts.bunny.net/css?family=roboto:400,500,700" |
	sed -e "s#, url([^)]*\.woff) format('woff')##" -e "s#$roboto#files/#g" >"$dest/roboto/roboto.css"
grep -o "files/[^)]*\.woff2" "$dest/roboto/roboto.css" | sort -u | while read -r file; do
	fetch "$roboto${file#files/}" "roboto/$file"
done
# These are the files of the @fontsource/roboto package, byte for byte, and the
# Open Font License they are under has to accompany them.
fetch "$npm/@fontsource/roboto@5.3.0/LICENSE" roboto/LICENSE

(cd "$dest" && find . -type f | LC_ALL=C sort | sed 's#^\./##' | xargs shasum -a 256) >vendor.sha256
echo "vendored $(wc -l <vendor.sha256 | tr -d ' ') files into web/$dest"
